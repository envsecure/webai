/**
 * App generator.
 *
 * Turns a natural-language prompt into a runnable starter project
 * (React front end + Express API + SQLite schema).
 *
 * The generator is intentionally local and deterministic so the clone works
 * offline. `generateWithModel()` is the seam for a hosted LLM: swap the
 * implementation and the rest of the app is unchanged.
 */

const KEYWORDS = [
  { id: 'todo', label: 'Task manager', match: /\b(todo|to-do|task|kanban|checklist|reminder)s?\b/i },
  { id: 'ecommerce', label: 'Online store', match: /\b(store|shop|e-?commerce|product|cart|checkout|retail)\w*\b/i },
  { id: 'blog', label: 'Blog', match: /\b(blog|article|post|cms|newsletter|writing)\w*\b/i },
  { id: 'chat', label: 'Chat app', match: /\b(chat|messag|chatbot|support|inbox|dms?)\w*\b/i },
  { id: 'crm', label: 'CRM dashboard', match: /\b(crm|customer|lead|sales|pipeline|deal)\w*\b/i },
  { id: 'booking', label: 'Booking app', match: /\b(book|booking|reservation|appointment|calendar|schedul)\w*\b/i },
  { id: 'social', label: 'Social feed', match: /\b(social|feed|timeline|follow|post)\w*\b/i },
  { id: 'portfolio', label: 'Portfolio', match: /\b(portfolio|resume|cv|designer|studio)\w*\b/i },
  { id: 'dashboard', label: 'Analytics dashboard', match: /\b(dashboard|analytics|report|metric|chart|admin)\w*\b/i },
  { id: 'marketplace', label: 'Marketplace', match: /\b(marketplace|listing|airbnb|classified|directory)\w*\b/i },
];

export function detectAppType(prompt) {
  const hit = KEYWORDS.find((k) => k.match.test(prompt || ''));
  return hit ? hit.id : 'starter';
}

export function titleFrom(prompt) {
  const clean = String(prompt || '')
    .replace(/^(build|create|make|generate|design|develop|write|give me|i want|can you)\s+/i, '')
    .replace(/^(me\s+)?(an|a|the)\s+/i, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!clean) return 'Starter app';
  const words = clean.split(' ').slice(0, 5);
  while (words.length > 2 && /^(and|or|with|for|to|of|in|on|that|the|a|an)$/i.test(words[words.length - 1])) {
    words.pop();
  }
  const short = words.join(' ');
  return short.charAt(0).toUpperCase() + short.slice(1);
}

/** The build plan shown in the builder UI while the app is generated. */
export function buildPlan(appType, prompt) {
  const base = [
    { step: 'Understanding your request', detail: prompt || 'No prompt supplied' },
    { step: 'Designing the data model', detail: 'SQLite tables, relations and seed data' },
    { step: 'Scaffolding the React interface', detail: 'Components, routing and styling' },
    { step: 'Wiring the Express API', detail: 'REST routes for every entity' },
    { step: 'Running checks', detail: 'Lint, type check and a production build' },
  ];
  const labels = {
    todo: ['Tasks with status, priority and due dates'],
    ecommerce: ['Products, cart and checkout flow'],
    blog: ['Posts, authors and comments'],
    chat: ['Conversations and messages'],
    crm: ['Contacts, companies and deals'],
    booking: ['Services, availability and bookings'],
    social: ['Profiles, posts and follows'],
    portfolio: ['Projects, skills and contact'],
    dashboard: ['Metrics, charts and filters'],
    marketplace: ['Listings, bookings and reviews'],
    starter: ['A single generic entity to get started'],
  };
  return [
    ...base.slice(0, 1),
    { step: 'Planning features', detail: labels[appType]?.[0] || labels.starter[0] },
    ...base.slice(1),
  ];
}

