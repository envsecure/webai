const reactComponentFor = (appType, name) => {
  const entity = {
    todo: 'task',
    ecommerce: 'product',
    blog: 'post',
    chat: 'conversation',
    crm: 'contact',
    booking: 'booking',
    social: 'post',
    portfolio: 'project',
    dashboard: 'metric',
    marketplace: 'listing',
    starter: 'item',
  }[appType];

  return `import { useEffect, useState } from 'react';
import { list${name}s, create${name} } from './api';

export default function ${name}List() {
  const [items, setItems] = useState([]);
  const [title, setTitle] = useState('');
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    list${name}s()
      .then(setItems)
      .finally(() => setLoading(false));
  }, []);

  async function onCreate(event) {
    event.preventDefault();
    if (!title.trim()) return;
    await create${name}({ title });
    setTitle('');
    setItems(await list${name}s());
  }

  if (loading) return <p className="muted">Loading ${entity}s…</p>;

  return (
    <section className="stack">
      <h2>${entity[0].toUpperCase()}${entity.slice(1)}s</h2>
      <form onSubmit={onCreate} className="row">
        <input
          value={title}
          onChange={(e) => setTitle(e.target.value)}
          placeholder="New ${entity}"
          aria-label="New ${entity}"
        />
        <button type="submit">Add</button>
      </form>
      <ul className="card-list">
        {items.map((item) => (
          <li key={item.id}>{item.title}</li>
        ))}
      </ul>
    </section>
  );
}
`;
};

const apiModuleFor = (name, path) => `const BASE = '/api/${path}';

async function request(url, options = {}) {
  const res = await fetch(url, {
    headers: { 'Content-Type': 'application/json' },
    ...options,
  });
  if (!res.ok) throw new Error(\`Request failed: \${res.status}\`);
  return res.status === 204 ? null : res.json();
}

export const list${name}s = () => request(BASE);
export const create${name} = (payload) =>
  request(BASE, { method: 'POST', body: JSON.stringify(payload) });
export const remove${name} = (id) => request(\`\${BASE}/\${id}\`, { method: 'DELETE' });
`;

const expressRouteFor = (name, path, table) => `import { Router } from 'express';
import { randomUUID } from 'node:crypto';

const router = Router();

router.get('/', (req, res) => {
  const rows = req.db.query('SELECT * FROM ${table} ORDER BY created_at DESC');
  res.json(rows);
});

router.post('/', (req, res) => {
  const now = new Date().toISOString();
  const item = {
    id: randomUUID(),
    title: String(req.body?.title || 'Untitled').slice(0, 200),
    description: String(req.body?.description || '').slice(0, 4000),
    status: 'active',
    created_at: now,
    updated_at: now,
  };
  req.db.run(
    \`INSERT INTO ${table} (id, title, description, status, created_at, updated_at)
     VALUES (?, ?, ?, ?, ?, ?)\`,
    [item.id, item.title, item.description, item.status, item.created_at, item.updated_at]
  );
  res.status(201).json(item);
});

router.delete('/:id', (req, res) => {
  req.db.run('DELETE FROM ${table} WHERE id = ?', [req.params.id]);
  res.status(204).end();
});

export default router;
`;

/**
 * Build the full file tree for a generated project.
 */
export function generateApp(prompt) {
  const appType = detectAppType(prompt);
  const title = titleFrom(prompt);
  const name = appType === 'ecommerce' ? 'Product' : appType[0].toUpperCase() + appType.slice(1);
  const table = {
    todo: 'tasks',
    ecommerce: 'products',
    blog: 'posts',
    chat: 'conversations',
    crm: 'contacts',
    booking: 'bookings',
    social: 'posts',
    portfolio: 'projects',
    dashboard: 'metrics',
    marketplace: 'listings',
    starter: 'items',
  }[appType];
  const apiPath = {
    todo: 'tasks',
    ecommerce: 'products',
    blog: 'posts',
    chat: 'conversations',
    crm: 'contacts',
    booking: 'bookings',
    social: 'posts',
    portfolio: 'projects',
    dashboard: 'metrics',
    marketplace: 'listings',
    starter: 'items',
  }[appType];

  const files = {
    'README.md': `# ${title}\n\nGenerated by the Lovable clone builder from the prompt:\n\n> ${prompt}\n\n## Stack\n\n- React 18 + Vite\n- Node.js + Express\n- SQLite\n\n## Run\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`,
    'server/schema.sql': schemaFor(appType),
    [`client/src/components/${name}List.jsx`]: reactComponentFor(appType, name),
    [`client/src/lib/api.js`]: apiModuleFor(name, apiPath),
    [`server/src/routes/${apiPath}.js`]: expressRouteFor(name, apiPath, table),
    'client/src/App.jsx': `import ${name}List from './components/${name}List';

export default function App() {
  return (
    <main className="app">
      <header>
        <h1>${title}</h1>
      </header>
      <${name}List />
    </main>
  );
}
`,
  };

  const plan = buildPlan(appType, prompt);
  const summary = `Built ${title} — a ${appType.replace(/^\w/, (c) => c.toUpperCase())} app with a React UI, an Express API and a SQLite schema (${table} table).`;

  return { appType, title, table, apiPath, files, plan, summary };
}

/**
 * Seam for a hosted LLM. Falls back to the local generator.
 * Implement this to stream real model output into the builder.
 */
export async function generateWithModel(prompt) {
  return generateApp(prompt);
}
